// 고정 공휴일: 매년 날짜가 동일 — 연도만 바꿔 자동 계산
function fixedHolidays(year) {
    return {
        [`${year}-01-01`]: "신정",
        [`${year}-03-01`]: "삼일절",
        [`${year}-05-05`]: "어린이날",
        [`${year}-06-06`]: "현충일",
        [`${year}-08-15`]: "광복절",
        [`${year}-10-03`]: "개천절",
        [`${year}-10-09`]: "한글날",
        [`${year}-12-25`]: "크리스마스",
    };
}

// 음력 기반 공휴일 + 대체공휴일 (연도별 수동 관리, ±1일 오차 가능)
const LUNAR_AND_SUBSTITUTE = {
    // 2025
    "2025-01-28": "설날 전날",
    "2025-01-29": "설날",
    "2025-01-30": "설날 다음날",
    "2025-05-06": "대체공휴일",       // 부처님오신날·어린이날 중복
    "2025-10-05": "추석 전날",
    "2025-10-06": "추석",
    "2025-10-07": "추석 다음날",
    "2025-10-08": "대체공휴일",       // 추석 전날(일요일) 대체
    // 2026
    "2026-02-16": "설날 전날",
    "2026-02-17": "설날",
    "2026-02-18": "설날 다음날",
    "2026-05-24": "부처님오신날",
    "2026-08-17": "광복절 대체공휴일", // 광복절(토요일) 대체
    "2026-09-24": "추석 전날",
    "2026-09-25": "추석",
    "2026-09-26": "추석 다음날",
    // 2027 이후 음력 공휴일 추가 필요 (고정 공휴일은 자동 계산됨)
};

export function getHoliday(isoDate) {
    if (LUNAR_AND_SUBSTITUTE[isoDate]) return LUNAR_AND_SUBSTITUTE[isoDate];
    const year = parseInt(isoDate.slice(0, 4));
    return fixedHolidays(year)[isoDate] || null;
}
